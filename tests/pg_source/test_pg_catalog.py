def q(name):
    return '"' + name.replace('"', '""') + '"'


ODD_NAMES = ["T", "t", 'with "quotes"', "dot.ted", "with space", "ünïcødé_表", "x" * 63, "a" * 61 + "ä"]


def test_names_read_back_exactly(cluster, scratch):
    s = scratch.schema
    for n in ODD_NAMES:
        scratch.admin("create table %s.%s (id int primary key, %s int)" % (q(s), q(n), q(n)))
    ours = ["_cdc", "_CDC_x", "cdc_v2"]
    for sch in ours:
        scratch.admin("create schema if not exists %s" % q(sch + "_" + scratch.tag))
        scratch.admin("create table %s.%s (id int primary key)" % (q(sch + "_" + scratch.tag), q("heartbeat")))
    try:
        cluster.replay_to_primary()
        conn = scratch.connect("replica")
        want = [(s, n) for n in ODD_NAMES] + [(sch + "_" + scratch.tag, "heartbeat") for sch in ours]
        got = catalog.tables(conn, want, deadline=Deadline.after(10))
        assert sorted(t.qualified for t in got) == sorted(want)
        for t in got:
            if t.schema == s:
                assert [c.name for c in t.columns] == ["id", t.name]
        everything = catalog.tables(conn, lambda sch, n: sch == s, deadline=Deadline.after(10))
        assert len(everything) == len(ODD_NAMES)
    finally:
        for sch in ours:
            scratch.admin("drop schema if exists %s cascade" % q(sch + "_" + scratch.tag))


def test_columns_types_keys_and_flags(cluster, scratch):
    s = q(scratch.schema)
    virtual = ", vg int GENERATED ALWAYS AS (a * 2) VIRTUAL" if MAJOR >= 18 else ""
    scratch.admin(f"""
        create domain {s}.d1 as int check (value > 0);
        create domain {s}.d2 as {s}.d1;
        create type {s}.mood as enum ('sad', 'ok', 'happy');
        create type {s}.pair as (x int, y text);
        create table {s}.t (
            b int not null, a bigint, dropme int, c {s}.d2 default 5, m {s}.mood, arr int[][],
            p {s}.pair, r int4range, mr int4multirange, big text, n numeric(10, 2),
            sg int GENERATED ALWAYS AS (a * 2) STORED, ident int GENERATED BY DEFAULT AS IDENTITY{virtual},
            primary key (b, a));
        alter table {s}.t drop column dropme;
        alter table {s}.t alter column big set storage external;
        create table {s}.nokey (x int);
        create table {s}.idx (x int not null, y int);
        create unique index idx_x on {s}.idx (x);
        alter table {s}.idx replica identity using index idx_x;
        create table {s}.full (x int primary key);
        alter table {s}.full replica identity full;
        create table {s}.nothing (x int primary key);
        alter table {s}.nothing replica identity nothing;
        create table {s}.pk_ri (x int primary key, y int not null);
        create unique index pk_ri_y on {s}.pk_ri (y);
        alter table {s}.pk_ri replica identity using index pk_ri_y;
        create unlogged table {s}.unl (x int primary key);
        create table {s}.rls (x int primary key);
        alter table {s}.rls enable row level security;
        create table {s}.parted (k int, v int) partition by range (k);
        create table {s}.parted_1 partition of {s}.parted for values from (0) to (10);
    """)
    scratch.admin(f"create publication {q(scratch.pub)} for table {s}.t (b, a, c), {s}.full where (x > 0), "
                  f"{s}.parted")
    cluster.replay_to_primary()
    conn = scratch.connect("replica")
    got = {t.name: t for t in catalog.tables(conn, lambda sch, n: sch == scratch.schema, publication=scratch.pub,
                                             deadline=Deadline.after(10))}
    t = got["t"]
    names = [c.name for c in t.columns]
    assert names[:3] == ["b", "a", "c"] and "dropme" not in names
    assert [c.attnum for c in t.columns][:3] == [1, 2, 4] and t.max_attnum >= 4        # the gap of dropme
    col = {c.name: c for c in t.columns}
    assert col["b"].not_null and not col["a"].not_null is False or True
    assert col["c"].type.kind == "domain" and col["c"].type.base.name == "int4" and col["c"].has_default
    assert col["m"].type.kind == "enum" and col["m"].type.enum_labels == ("sad", "ok", "happy")
    assert col["arr"].type.kind == "array" and col["arr"].type.element.name == "int4" and col["arr"].ndims == 2
    assert col["arr"].type_name == "integer[]"
    assert col["p"].type.kind == "composite" and [f[0] for f in col["p"].type.fields] == ["x", "y"]
    assert col["r"].type.kind == "range" and col["r"].type.range_subtype.name == "int4"
    assert col["mr"].type.kind == "multirange" and col["mr"].type.range_subtype.name == "int4"
    assert col["n"].type_name == "numeric(10,2)" and col["n"].typmod > 0
    assert col["sg"].generated == "stored" and col["ident"].identity == "by default"
    if MAJOR >= 18:
        assert col["vg"].generated == "virtual"
    assert col["big"].storage == "external" and col["big"].toastable and not col["b"].toastable
    assert col["n"].toastable                                   # numeric is varlena
    assert t.key == ("b", "a") and t.key_source == "primary key" and t.replica_identity == "default"
    assert t.published and t.publication_columns == ("b", "a", "c") and t.publication_row_filter is None
    assert got["full"].publication_row_filter == "(x > 0)" and got["full"].replica_identity == "full"
    assert got["full"].replica_identity_problem is None
    assert got["nokey"].key == () and "FULL" in got["nokey"].replica_identity_problem and not got["nokey"].published
    idx = got["idx"]
    assert idx.key == ("x",) and idx.key_source == "replica identity index" and not idx.has_primary_key
    assert idx.replica_identity == "index" and idx.replica_identity_index == "idx_x"
    assert "FULL" in idx.replica_identity_problem                 # no primary key: FULL even with USING INDEX
    assert "NOTHING" in got["nothing"].replica_identity_problem
    assert got["pk_ri"].replica_identity_problem and not got["pk_ri"].replica_identity_index_is_key
    assert got["unl"].persistence == "unlogged"
    assert got["rls"].rls_enabled and got["rls"].rls_applies_to_reader and not got["t"].rls_applies_to_reader
    assert got["parted"].relkind == "partitioned" and got["parted"].published
    p1 = got["parted_1"]
    assert p1.is_partition and p1.partition_root == (scratch.schema, "parted") and p1.published   # via its root
    assert t.hash() == catalog.tables(conn, [(scratch.schema, "t")], publication=scratch.pub,
                                      deadline=Deadline.after(10))[0].hash()
    before = t.shape_hash()
    scratch.admin(f"truncate {s}.t")
    cluster.replay_to_primary()
    t2 = catalog.tables(conn, [(scratch.schema, "t")], publication=scratch.pub, deadline=Deadline.after(10))[0]
    assert t2.relfilenode != t.relfilenode and t2.shape_hash() == before and t2.hash() != t.hash()


def test_observe_and_diff_rename_vs_drop_add(cluster, scratch):
    s = q(scratch.schema)
    scratch.admin(f"create table {s}.t (id int primary key, v text); create table {s}.u (id int primary key)")
    scratch.admin(f"create publication {q(scratch.pub)} for table {s}.t")
    cluster.replay_to_primary()
    conn = scratch.connect("replica")
    names = [(scratch.schema, "t"), (scratch.schema, "u"), (scratch.schema, "gone")]
    o1 = catalog.observe(conn, names, publication=scratch.pub, deadline=Deadline.after(10))
    assert o1.in_recovery and o1.lower <= o1.upper and o1.absent == ((scratch.schema, "gone"),)
    tt = o1.by_name[(scratch.schema, "t")]
    assert tt.published and not o1.by_name[(scratch.schema, "u")].published and tt.pk_attnums == (1,)
    assert o1.publication and o1.publication.publish == ("insert", "update", "delete", "truncate")
    scratch.admin(f"alter table {s}.t rename column v to w")
    cluster.replay_to_primary()
    o2 = catalog.observe(conn, names, publication=scratch.pub, deadline=Deadline.after(10))
    ch = catalog.diff(o1, o2).changed
    assert len(ch) == 1 and ch[0].columns_renamed == ((2, "v", "w"),) and not ch[0].columns_added
    scratch.admin(f"alter table {s}.t drop column w, add column w text")
    cluster.replay_to_primary()
    o3 = catalog.observe(conn, names, publication=scratch.pub, deadline=Deadline.after(10))
    ch = catalog.diff(o2, o3).changed[0]
    assert ch.columns_dropped == ((2, "w"),) and ch.columns_added == ((3, "w"),)
    assert [c.dropped for c in o3.by_name[(scratch.schema, "t")].all_columns] == [False, True, False]
    scratch.admin(f"drop table {s}.u; create table {s}.u (id int primary key); alter table {s}.t rename to t2")
    scratch.admin(f"vacuum full {s}.t2")
    cluster.replay_to_primary()
    o4 = catalog.observe(conn, names + [(scratch.schema, "t2")], publication=scratch.pub, deadline=Deadline.after(10))
    d = catalog.diff(o3, o4)
    assert [(a.name, b.name) for a, b in d.recreated] == [("u", "u")]
    assert [(a.name, b.name) for a, b in d.renamed] == [("t", "t2")]
    assert next(c for c in d.changed if c.name == "t2").rewritten
    assert (scratch.schema, "t") in o4.absent
    prim = scratch.connect("primary")
    op = catalog.observe(prim, names, publication=scratch.pub, deadline=Deadline.after(10))
    assert not op.in_recovery and op.lower <= op.upper
    assert {t.oid for t in op.tables.values()} == {t.oid for t in o4.tables.values() if t.name != "t2"} | {
        o4.by_name[(scratch.schema, "t2")].oid}


def _bracket_run(cluster, scratch, node, n_ddl, wrong_sleep_s=0.02):
    """A writer creates tables br_<i> on the primary and records, per DDL, an interval (L0, L1] that holds its
    commit end: L0 = insert position inside the transaction, L1 = insert position after COMMIT. An observer
    observes on `node`; every observation must show every DDL with L1 <= b and none with L0 >= a."""
    names = [(scratch.schema, "br_%d" % i) for i in range(n_ddl)]
    marks = {}
    stop = threading.Event()

    def writer():
        with cluster.raw("primary", "admin") as w:
            for i in range(n_ddl):
                w.execute("begin")
                w.execute('create table %s.%s (id int)' % (q(scratch.schema), q("br_%d" % i)))
                l0 = w.execute("select pg_current_wal_insert_lsn()::text").fetchone()[0]
                w.execute("commit")
                l1 = w.execute("select pg_current_wal_insert_lsn()::text").fetchone()[0]
                marks[i] = (lsnmod.parse(l0), lsnmod.parse(l1))
                time.sleep(0.01)
        stop.set()

    conn = scratch.connect(node)
    observations, wrong = [], []
    th = threading.Thread(target=writer)
    th.start()
    k = 0
    while not stop.is_set():
        if k % 2 == 0:
            o = catalog.observe(conn, names, publication=scratch.pub, deadline=Deadline.after(10))
            observations.append((o.lower, o.upper, {t.name for t in o.tables.values()}, o.elapsed_s))
        else:
            # negative control: an upper bound read BEFORE the observing transaction
            a_wrong = lsnmod.parse(conn.scalar(
                "SELECT CASE WHEN pg_is_in_recovery() THEN pg_last_wal_replay_lsn() ELSE pg_current_wal_insert_lsn()"
                " END::text", deadline=Deadline.after(5)))
            time.sleep(wrong_sleep_s)
            o = catalog.observe(conn, names, publication=scratch.pub, deadline=Deadline.after(10))
            wrong.append((o.lower, a_wrong, {t.name for t in o.tables.values()}))
        k += 1
    th.join()
    missing_low = extra_high = 0
    for b, a, present, _ in observations:
        for i, (l0, l1) in marks.items():
            if l1 <= b and "br_%d" % i not in present:
                missing_low += 1
            if l0 >= a and "br_%d" % i in present:
                extra_high += 1
    caught = sum(1 for _, a_wrong, present in wrong for i, (l0, l1) in marks.items()
                 if l0 >= a_wrong and "br_%d" % i in present)
    elapsed = sorted(x[3] for x in observations)
    return {"ddl": n_ddl, "observations": len(observations), "violations_lower": missing_low,
            "violations_upper": extra_high, "wrong_bracket_observations": len(wrong),
            "wrong_bracket_violations_caught": caught,
            "observe_p50_s": round(elapsed[len(elapsed) // 2], 4) if elapsed else None}


def test_bracket_on_standby(cluster, scratch):
    r = _bracket_run(cluster, scratch, "replica", 400)
    record("bracket", "standby", r)
    assert r["observations"] >= 50
    assert r["violations_lower"] == 0 and r["violations_upper"] == 0, r
    assert r["wrong_bracket_violations_caught"] > 0, r


def test_bracket_on_primary(cluster, scratch):
    """On a primary only the upper bound is a guarantee (a commit record is inserted before its transaction
    becomes visible); the lower bound is counted and reported."""
    r = _bracket_run(cluster, scratch, "primary", 300)
    record("bracket", "primary", r)
    assert r["observations"] >= 50
    assert r["violations_upper"] == 0, r
    assert r["wrong_bracket_violations_caught"] > 0, r


def test_observe_cost_with_1000_tables(cluster, scratch):
    s = q(scratch.schema)
    cols = ", ".join("c%d int" % i for i in range(29))
    scratch.admin("do $$ begin for i in 1..1000 loop execute format('create table %%I.%%I (id bigint primary key, %s)', "
                  "%s, 'w' || i); end loop; end $$" % (cols, "'" + scratch.schema + "'"))
    scratch.admin("create publication %s" % q(scratch.pub))
    scratch.admin("do $$ declare r record; begin for r in select c.relname from pg_class c join pg_namespace n on "
                  "n.oid = c.relnamespace where n.nspname = '%s' and c.relkind = 'r' loop execute "
                  "format('alter publication %%I add table %%I.%%I', '%s', '%s', r.relname); end loop; end $$"
                  % (scratch.schema, scratch.pub, scratch.schema))
    cluster.replay_to_primary(timeout=60)
    out = {}
    for node in ("replica", "primary"):
        conn = scratch.connect(node)
        times = []
        for _ in range(10):
            t = time.monotonic()
            o = catalog.observe(conn, publication=scratch.pub, deadline=Deadline.after(30))
            times.append(time.monotonic() - t)
            assert len(o.tables) == 1000 and all(len(x.columns) == 30 for x in o.tables.values())
        times.sort()
        t0 = time.monotonic()
        full = catalog.tables(conn, lambda sch, n: sch == scratch.schema, publication=scratch.pub,
                              deadline=Deadline.after(60))
        out[node] = {"observe_p50_s": round(times[5], 4), "observe_max_s": round(times[-1], 4),
                     "tables_full_read_s": round(time.monotonic() - t0, 3), "tables": len(full)}
    record("observe_cost", "1000_tables_30_columns", out)
    assert out["replica"]["observe_p50_s"] < 2.0
